def generate_emoji_txt(mode):
    from settings import bot_settings
    lines = []
    if mode == "flags":
        for code, data in bot_settings.get("premium_flags", {}).items():
            char = data.get("char", "")
            eid = data.get("id", "")
            iso = data.get("iso", "")
            name = data.get("name", "")
            line = f"{char} ({code}) ({iso}) {name} {{\"emoji\":\"{char}\",\"id\":\"{eid}\"}}"
            lines.append(line)
    else:
        for name, data in bot_settings.get("premium_apps", {}).items():
            char = data.get("char", "")
            eid = data.get("id", "")
            disp_name = data.get("name", name)
            line = f"{char} {disp_name} {{\"emoji\":\"{char}\",\"id\":\"{eid}\"}}"
            lines.append(line)
    if not lines: return None
    return "\n".join(lines).encode('utf-8')


